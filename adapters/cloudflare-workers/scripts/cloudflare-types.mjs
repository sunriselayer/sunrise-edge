import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const cliVersion = "1.0.0-beta.13";
const definitions = [
  ["ingress", "worker-configuration.d.ts", "Env"],
  ["validator", "validator-configuration.d.ts", "ValidatorEnv"],
  ["certified", "certified-configuration.d.ts", "CertifiedRelayEnv"],
  ["sql", "test/validator/sql-env.d.ts", "SqlProbeEnv"],
  ["contract", "test/validator/contract-env.d.ts", "ContractTestEnv"],
];
const check = process.argv.length === 3 && process.argv[2] === "--check";
if ((!check && process.argv.length !== 2) || Number(process.versions.node.split(".")[0]) !== 24) {
  throw new Error("Use Node 24: cloudflare-types.mjs [--check]");
}
const hash = (value) => createHash("sha256").update(value).digest("hex");
const profileBytes = await readFile(path.join(root, "cloudflare-profiles.json"));
const profiles = JSON.parse(profileBytes);
const rendererSha256 = hash(await readFile(fileURLToPath(import.meta.url)));
const manifest = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
if (Object.keys(profiles).join(",") !== definitions.map(([name]) => name).join(",")) {
  throw new Error("The exact five Cloudflare profiles are required");
}
function command(argv, cwd) {
  const result = spawnSync("cf", argv, {
    cwd,
    env: { ...process.env, CF_SEND_TELEMETRY: "false", DO_NOT_TRACK: "1", CI: "true", NO_COLOR: "1" },
    encoding: "utf8",
    timeout: 60_000,
    maxBuffer: 1024 * 1024,
    shell: false,
  });
  if (result.error || result.status !== 0 || result.signal) {
    throw new Error(`cf ${argv.join(" ")} failed: ${result.error?.message ?? result.stderr}`);
  }
  return result.stdout.trim();
}
if (command(["--version"], root) !== cliVersion) {
  throw new Error(`Install exact external cf@${cliVersion}; this script never installs tools`);
}
const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const assets = [
  ["*.txt", "string"], ["*.html", "string"], ["*.sql", "string"],
  ["*.bin", "ArrayBuffer"], ["*.wasm", "WebAssembly.Module"],
  ["*.wasm?module", "WebAssembly.Module"],
];
const expected = [];
for (const [name, output, envName] of definitions) {
  const directory = path.join(root, "profiles", name);
  const leaf = await readFile(path.join(directory, "cloudflare.config.ts"), "utf8");
  const expectedLeaf = `import profiles from "../../cloudflare-profiles.json" with { type: "json" };\n\n// Parsed as plain configuration by the pinned cf CLI and Vitest loader.\nexport default profiles.${name};\n`;
  if (leaf !== expectedLeaf) throw new Error(`Unrecognized config leaf: ${name}`);
  // cf validates the actual schema. Its invariant InferEnv import template
  // alone proves neither concrete resolved binding types nor stale inputs.
  command(["workers", "types", "--include-runtime=false"], directory);
  const generated = await readFile(path.join(directory, ".cloudflare/types/index.d.ts"), "utf8");
  const rawTemplate = `/* eslint-disable */\n// Generated by @cloudflare/config\ntype __Config = import("cf/config").UnwrapConfig<typeof import("../../cloudflare.config").default>;\ntype __WorkerConfig = import("cf/config").UnwrapConfig<__Config["worker"]>;\ntype __Env = import("cf/config").InferEnv<__WorkerConfig>;\n\ndeclare namespace Cloudflare {\n\tinterface GlobalProps {\n\t\tmainModule: import("cf/config").InferMainModule<__WorkerConfig>;\n\t\tdurableNamespaces: import("cf/config").InferDurableNamespaces<__WorkerConfig>;\n\t}\n\tinterface Env extends __Env {}\n}\ninterface Env extends Cloudflare.Env {}`;
  if (generated.replaceAll("\r\n", "\n").trim() !== rawTemplate) {
    throw new Error(`cf template changed for ${name}; review the renderer`);
  }
  const worker = profiles[name].worker;
  const entry = path.resolve(directory, worker.entrypoint);
  if (!entry.startsWith(root + path.sep) || !entry.endsWith(".ts")) throw new Error(`Invalid entrypoint: ${name}`);
  let module = path.relative(path.dirname(path.join(root, output)), entry).split(path.sep).join("/").replace(/\.ts$/, "");
  if (!module.startsWith(".")) module = "./" + module;
  const fields = [];
  const strings = [];
  const classes = Object.keys(worker.exports ?? {});
  for (const className of classes) {
    const declaration = worker.exports[className];
    if (!identifier.test(className) || declaration.type !== "durable-object" || declaration.storage !== "sqlite" || declaration.state !== undefined) {
      throw new Error(`Only existing SQLite DO exports are supported: ${name}/${className}`);
    }
  }
  for (const [bindingName, binding] of Object.entries(worker.env)) {
    if (!identifier.test(bindingName)) throw new Error(`Invalid binding name: ${bindingName}`);
    let type;
    switch (binding.type) {
      case "text":
        if (typeof binding.value !== "string") throw new Error("Text binding must contain a string");
        type = "string"; strings.push(bindingName); break;
      case "secret": type = "string"; strings.push(bindingName); break;
      case "worker":
        if (typeof binding.worker !== "string" || !/^[A-Za-z0-9_-]+$/.test(binding.worker) || binding.exportName !== undefined) throw new Error("Unsupported service binding");
        type = `Fetcher /* ${binding.worker} */`; break;
      case "durable-object":
        if (binding.worker !== worker.name || !classes.includes(binding.exportName)) throw new Error("DO must reference an existing class in this same Worker");
        type = `DurableObjectNamespace<import(${JSON.stringify(module)}).${binding.exportName}>`; break;
      default: throw new Error(`Unsupported binding type ${binding.type}; extend the explicit renderer`);
    }
    fields.push(`\t${bindingName}: ${type};`);
  }
  const fingerprint = hash(JSON.stringify({ name, output, envName, profileSha256: hash(profileBytes), leafSha256: hash(leaf), rendererSha256, cliVersion, workersTypesVersion: manifest.devDependencies["@cloudflare/workers-types"] }));
  const lines = ["/* eslint-disable */", `// Generated by cf@${cliVersion} and scripts/cloudflare-types.mjs; input-sha256: ${fingerprint}`, `interface __BaseEnv_${envName} {`, ...fields, "}", "declare namespace Cloudflare {", "\tinterface GlobalProps {", `\t\tmainModule: typeof import(${JSON.stringify(module)});`];
  if (classes.length) lines.push(`\t\tdurableNamespaces: ${classes.map((value) => JSON.stringify(value)).join(" | ")};`);
  lines.push("\t}", `\tinterface Env extends __BaseEnv_${envName} {}`, "}", `interface ${envName} extends __BaseEnv_${envName} {}`);
  if (strings.length) lines.push("declare namespace NodeJS {", "\tinterface ProcessEnv {", ...strings.map((value) => `\t\t${value}: string;`), "\t}", "}");
  for (const [pattern, type] of assets) lines.push(`declare module ${JSON.stringify(pattern)} {`, `\tconst value: ${type};`, "\texport default value;", "}");
  expected.push([output, lines.join("\n") + "\n"]);
}
// Validate/render all five first. --check never replaces committed declarations.
for (const [output, content] of expected) {
  const destination = path.join(root, output);
  if (check) {
    const current = await readFile(destination, "utf8");
    if (current !== content) throw new Error(`${output} is stale; run npm run types`);
  } else await writeFile(destination, content);
}
